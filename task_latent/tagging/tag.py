"""Annotate IBC conditions with the stimulus and response ontology.

Run with ``python -m task_latent.tagging.tag``. Use ``--task TASK`` to
restrict the run and ``--help`` for input/output options. Each completed
condition is checkpointed to a separate JSON file; existing files are not
overwritten unless ``--overwrite`` is supplied.
"""

import argparse
import ast
import json
import os
import tempfile
from dataclasses import asdict, dataclass
from enum import Enum
from pathlib import Path
from typing import Any

from ollama import chat
from pydantic import BaseModel, ConfigDict, Field

from task_latent.tagging.ontology import (
    RESPONSE_EFFECTOR,
    RESPONSE_LATERALITY,
    STIMULUS_DYNAMICS,
    STIMULUS_LATERALITY,
    STIMULUS_MODALITY,
    STIMULUS_TYPE,
    ConditionOntology,
    ResponseEffector,
    ResponseLaterality,
    StimulusDynamics,
    StimulusLaterality,
    StimulusModality,
    StimulusType,
)

MODEL = "qwen3.8:27b"
ROOT = Path(__file__).resolve().parents[2]
DEFAULT_INPUT = ROOT / "task_latent/ibc_conditions.json"
DEFAULT_OUTPUT = ROOT / "task_latent/tagging/annotations.json"


@dataclass(frozen=True)
class ConditionAnnotation:
    """
    Annotations describing an experimental condition.

    Attributes:
        name: The name of the condition.
        task: The task to which the condition belongs.
        cognitive_atlas: Original experimenter-defined condition labels.
        stimulus_type: Types of stimuli associated with the condition, along with confidence and optional comment.
        stimulus_modality: Modality of the stimuli, along with confidence and optional comment.
        stimulus_laterality: Laterality of the stimuli, along with confidence and optional comment.
        stimulus_dynamics: Dynamics of the stimuli, along with confidence and optional comment.
        response_effector: Effector used for the response, along with confidence and optional comment.
        response_laterality: Laterality of the response, along with confidence and optional comment.
        response_structure: Temporal or organizational structure of the response, along with confidence and optional comment.
    """

    name: str
    task: str

    # Original experimenter-defined condition
    cognitive_atlas: tuple[str, ...]

    # Stimulus annotations
    stimulus_type: tuple[tuple[StimulusType, float, str | None], ...]
    stimulus_modality: tuple[StimulusModality, float, str | None]
    stimulus_laterality: tuple[StimulusLaterality, float, str | None]
    stimulus_dynamics: tuple[StimulusDynamics, float, str | None]

    # Response annotations
    response_effector: tuple[ResponseEffector, float, str | None]
    response_laterality: tuple[ResponseLaterality, float, str | None]


class AnnotationItem[T: Enum](BaseModel):
    """
    An individual annotation item within the model's response.

    Attributes:
        ontology_term: The ontology term being annotated.
        annotation_confidence: The model's confidence in the annotation, between 0 and 1.
        annotation_comment: Optional comment providing additional context or justification for the annotation. If applicable,
        provide what additional evidence would be needed to support a different annotation.

    """

    model_config = ConfigDict(extra="forbid")

    ontology_term: T
    annotation_confidence: float = Field(..., ge=0, le=1)
    annotation_comment: str | None = None


class AnnotationResponse(BaseModel):
    """The fields generated by the model; identity and atlas tags come from input."""

    model_config = ConfigDict(extra="forbid")

    stimulus_type: list[AnnotationItem[StimulusType]]
    stimulus_modality: AnnotationItem[StimulusModality]
    stimulus_laterality: AnnotationItem[StimulusLaterality]
    stimulus_dynamics: AnnotationItem[StimulusDynamics]
    response_effector: AnnotationItem[ResponseEffector]
    response_laterality: AnnotationItem[ResponseLaterality]


ONTOLOGIES = (
    STIMULUS_TYPE,
    STIMULUS_MODALITY,
    STIMULUS_LATERALITY,
    STIMULUS_DYNAMICS,
    RESPONSE_EFFECTOR,
    RESPONSE_LATERALITY,
)

TAG_PROMPT = """\
Annotate the target condition using the ontology and evidence in the JSON below.
Return only the requested structured annotation. Use only the allowed enum values.

Return a JSON object with all seven fields shown below. Each annotation item is
an object containing ontology_term (an allowed value for that field),
annotation_confidence (a number between 0 and 1 reflecting your confidence),
and annotation_comment (a short evidence-based explanation or null). For uncertain
annotations, use the comment to describe what evidence is missing or would
support a different value. Confidence is your estimate, not a measured probability.
stimulus_type is an array of annotation items; the other
five fields each contain exactly one annotation item. For example, the following
illustrates the shape only; choose values based on the actual condition:
{{
    "stimulus_type": [{{"ontology_term": "language", "annotation_confidence": 0.9, "annotation_comment": "Written words are presented."}}],
    "stimulus_modality": {{"ontology_term": "visual", "annotation_confidence": 0.9, "annotation_comment": null}},
    "stimulus_laterality": {{"ontology_term": "unspecified", "annotation_confidence": 0.5, "annotation_comment": "Presentation side is not stated."}},
    "stimulus_dynamics": {{"ontology_term": "unspecified", "annotation_confidence": 0.5, "annotation_comment": null}},
    "response_effector": {{"ontology_term": "hand", "annotation_confidence": 0.9, "annotation_comment": "The participant presses a button."}},
    "response_laterality": {{"ontology_term": "right", "annotation_confidence": 0.9, "annotation_comment": null}}
}}

Annotate stimuli and responses for the target condition, not other task phases.
Use the task description as context, but do not assume every task-wide stimulus
or response occurs during this condition. Cognitive atlas tags are context, not
proof of a stimulus or response. Do not invent details. Choose unspecified when
the available evidence does not establish a category; use none according to
the relevant ontology definition, not as a substitute for unknown. Use empty arrays for
stimulus_type or response_structure if no category is supported; otherwise list
all supported values without duplicates. Do not mix unspecified with specific
values in an array. Stimulus and response laterality refer to different things.

Evidence and allowed terms:
{evidence}
"""


def ontology_guidance(
    ontology: ConditionOntology, enum_type: type[Enum]
) -> dict[str, Any]:
    """Expose the same enum values and term definitions used by the schema."""
    terms = {}
    for member in enum_type:
        term = ontology.terms.get(member.value)
        terms[member.value] = {
            "description": term.description
            if term
            else "Not established by the evidence.",
            "examples": list(term.examples) if term else [],
            "annotation_guidance": term.annotation_guidance if term else None,
        }
    return {"description": ontology.description, "terms": terms}


def tag_condition(
    condition_label: str,
    task_label: str,
    condition_description: str,
    task_description: str,
    cognitive_atlas_labels: list[str],
    *,
    model: str = MODEL,
) -> ConditionAnnotation:
    """Create a validated annotation without allowing the model to alter identity or tags."""
    enum_types = (
        StimulusType,
        StimulusModality,
        StimulusLaterality,
        StimulusDynamics,
        ResponseEffector,
        ResponseLaterality,
    )
    evidence = {
        "task": task_label,
        "condition": condition_label,
        "task_description": task_description,
        "condition_description": condition_description,
        "cognitive_atlas_terms": cognitive_atlas_labels,
        "ontology": {
            ontology.name: ontology_guidance(ontology, enum_type)
            for ontology, enum_type in zip(ONTOLOGIES, enum_types, strict=True)
        },
    }
    response = chat(
        model=model,
        messages=[
            {
                "role": "user",
                "content": TAG_PROMPT.format(
                    evidence=json.dumps(evidence, ensure_ascii=False, indent=2)
                ),
            }
        ],
        format=AnnotationResponse.model_json_schema(),
        options={"temperature": 0},
        think=False,
    )
    if response.message.content is None:
        raise ValueError("No response message content received from the model.")

    annotation = AnnotationResponse.model_validate_json(response.message.content)
    return ConditionAnnotation(
        name=condition_label,
        task=task_label,
        cognitive_atlas=tuple(cognitive_atlas_labels),
        stimulus_type=tuple(
            (item.ontology_term, item.annotation_confidence, item.annotation_comment)
            for item in annotation.stimulus_type
        ),
        stimulus_modality=(
            annotation.stimulus_modality.ontology_term,
            annotation.stimulus_modality.annotation_confidence,
            annotation.stimulus_modality.annotation_comment,
        ),
        stimulus_laterality=(
            annotation.stimulus_laterality.ontology_term,
            annotation.stimulus_laterality.annotation_confidence,
            annotation.stimulus_laterality.annotation_comment,
        ),
        stimulus_dynamics=(
            annotation.stimulus_dynamics.ontology_term,
            annotation.stimulus_dynamics.annotation_confidence,
            annotation.stimulus_dynamics.annotation_comment,
        ),
        response_effector=(
            annotation.response_effector.ontology_term,
            annotation.response_effector.annotation_confidence,
            annotation.response_effector.annotation_comment,
        ),
        response_laterality=(
            annotation.response_laterality.ontology_term,
            annotation.response_laterality.annotation_confidence,
            annotation.response_laterality.annotation_comment,
        ),
    )


def parse_cognitive_atlas_labels(value: Any) -> list[str]:
    """Accept real lists and the Python-list strings in the IBC metadata."""
    if value is None:
        return []
    if isinstance(value, str):
        try:
            value = ast.literal_eval(value)
        except (ValueError, SyntaxError) as exc:
            raise ValueError("Cognitive atlas terms must be a list of strings") from exc
    if not isinstance(value, list) or not all(isinstance(item, str) for item in value):
        raise ValueError("Cognitive atlas terms must be a list of strings")
    return value


def prepare_conditions(metadata: dict[str, Any], tasks: list[str] | None = None):
    """Validate inputs before starting any expensive Ollama requests."""
    if tasks is not None:
        invalid = [
            task
            for task in tasks
            if task not in metadata or not metadata[task].get("keep")
        ]
        if invalid:
            raise ValueError(f"Unknown or excluded tasks: {', '.join(invalid)}")
    selected = set(tasks) if tasks is not None else None
    conditions = []
    for task, info in metadata.items():
        if not info.get("keep") or (selected is not None and task not in selected):
            continue
        description = info.get("description")
        if not isinstance(description, str) or not description.strip():
            raise ValueError(f"Missing task description for {task}")
        labels = info.get("condition")
        if not isinstance(labels, list) or not all(
            isinstance(label, str) and label for label in labels
        ):
            raise ValueError(f"Invalid condition list for {task}")
        if len(labels) != len(set(labels)):
            raise ValueError(f"Duplicate condition labels for {task}")
        for label in labels:
            condition_description = info.get("condition_descriptions", {}).get(label)
            if (
                not isinstance(condition_description, str)
                or not condition_description.strip()
            ):
                raise ValueError(f"Missing condition description for {task}/{label}")
            tags = info.get("condition_tags", {})
            if label not in tags:
                raise ValueError(f"Missing cognitive atlas terms for {task}/{label}")
            try:
                atlas_labels = parse_cognitive_atlas_labels(tags[label])
            except ValueError as exc:
                raise ValueError(
                    f"Invalid cognitive atlas terms for {task}/{label}"
                ) from exc
            conditions.append(
                (task, label, description, condition_description, atlas_labels)
            )
    return conditions


def save_checkpoint(annotations: dict[str, dict[str, Any]], output_path: Path) -> None:
    """Atomically save all successfully generated condition annotations."""
    output_path.parent.mkdir(parents=True, exist_ok=True)
    temporary_path = None
    try:
        with tempfile.NamedTemporaryFile(
            mode="w", encoding="utf-8", dir=output_path.parent, delete=False
        ) as file:
            temporary_path = Path(file.name)
            json.dump(annotations, file, ensure_ascii=False, indent=2)
            file.write("\n")
        os.replace(temporary_path, output_path)
    finally:
        if temporary_path is not None:
            temporary_path.unlink(missing_ok=True)


def annotate_conditions(
    metadata: dict[str, Any],
    output_path: Path,
    *,
    tasks: list[str] | None = None,
    model: str = MODEL,
    overwrite: bool = False,
) -> dict[str, dict[str, ConditionAnnotation]]:
    """Tag each kept condition and preserve validated results after each request."""
    output_path = Path(output_path)
    if output_path.exists() and not overwrite:
        raise FileExistsError(
            f"Output already exists: {output_path}; use --overwrite to replace it"
        )
    conditions = prepare_conditions(metadata, tasks)
    annotations: dict[str, dict[str, ConditionAnnotation]] = {}
    for (
        task,
        label,
        task_description,
        condition_description,
        atlas_labels,
    ) in conditions:
        print(f"Tagging {task}/{label}", flush=True)
        try:
            annotation = tag_condition(
                label,
                task,
                condition_description,
                task_description,
                atlas_labels,
                model=model,
            )
            annotations.setdefault(task, {})[label] = annotation
            save_checkpoint(
                {
                    t: {c: asdict(value) for c, value in entries.items()}
                    for t, entries in annotations.items()
                },
                output_path,
            )
        except Exception as exc:
            raise RuntimeError(f"Failed to annotate {task}/{label}: {exc}") from exc
    return annotations


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--input", type=Path, default=DEFAULT_INPUT, help="Condition metadata JSON"
    )
    parser.add_argument(
        "--output", type=Path, default=DEFAULT_OUTPUT, help="Annotation output JSON"
    )
    parser.add_argument(
        "--task", action="append", help="Only annotate this kept task; repeatable"
    )
    parser.add_argument("--model", default=MODEL, help="Ollama model name")
    parser.add_argument(
        "--overwrite", action="store_true", help="Replace an existing output"
    )
    args = parser.parse_args()
    if args.input.resolve() == args.output.resolve():
        parser.error("Input and output must be different files")
    with args.input.open(encoding="utf-8") as file:
        metadata = json.load(file)
    annotations = annotate_conditions(
        metadata,
        args.output,
        tasks=args.task,
        model=args.model,
        overwrite=args.overwrite,
    )
    print(f"Saved {sum(map(len, annotations.values()))} annotations to {args.output}")


if __name__ == "__main__":
    main()
